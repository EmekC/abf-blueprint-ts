  const noKind = planBuild(ir, { ...base, createKinds: ["Blueprint"], manifests: new Map(), missing: new Set(["/TestMod/S_Entry"]) });
  assert.deepEqual(noKind.diagnostics.map((d) => d.code), ["ABFC2044"]);
