// `.abfc/tags.d.ts`: the gameplay tags of the game and of the mod as typed constants, plus the keys of `AbfcKnownGameplayTags`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** Words that cannot be the name of a `declare const` (and a few globals it must not shadow). */
const RESERVED = new Set([
  "arguments", "await", "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
  "eval", "export", "extends", "false", "finally", "for", "function", "if", "implements", "import", "in", "Infinity", "instanceof",
  "interface", "let", "NaN", "new", "null", "package", "private", "protected", "public", "return", "static", "super", "switch", "this",
  "throw", "true", "try", "typeof", "undefined", "var", "void", "while", "with", "yield", "globalThis",
  // Globals of the ES2023 lib: `declare const Map` would merge with the lib's declaration (and `Map.Foo` would not type-check).
  "AggregateError", "Array", "ArrayBuffer", "Atomics", "BigInt", "BigInt64Array", "BigUint64Array", "Boolean", "DataView", "Date",
  "decodeURI", "decodeURIComponent", "encodeURI", "encodeURIComponent", "Error", "escape", "EvalError", "FinalizationRegistry",
  "Float32Array", "Float64Array", "Function", "Int16Array", "Int32Array", "Int8Array", "isFinite", "isNaN", "Iterator", "JSON", "Map",
  "Math", "Number", "Object", "parseFloat", "parseInt", "Promise", "Proxy", "RangeError", "ReferenceError", "Reflect", "RegExp", "Set",
  "SharedArrayBuffer", "String", "Symbol", "SyntaxError", "TypeError", "Uint16Array", "Uint32Array", "Uint8Array", "Uint8ClampedArray",
  "unescape", "URIError", "WeakMap", "WeakRef", "WeakSet",
]);

const byText = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** The tags of one ini file: the `Tag="..."` of every `GameplayTagList=(...)` line (`+` prefix optional), CRLF or LF. */
export function parseTagsIni(text: string): string[] {
  const out: string[] = [];
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*\+?\s*GameplayTagList\s*=\s*\(\s*Tag\s*=\s*"([^"]+)"/.exec(line);
    if (m !== null && !out.includes(m[1]!)) out.push(m[1]!);
  }
  return out;
}

interface Node {
  tag: boolean;
  kids: Map<string, Node>;
}

const member = (name: string): string => (IDENT.test(name) ? name : JSON.stringify(name));

function renderNode(path: string, n: Node, indent: string): string {
  const kids = [...n.kids].sort(([a], [b]) => byText(a, b));
  const body =
    kids.length === 0
      ? ""
      : `{\n${kids.map(([name, k]) => `${indent}  readonly ${member(name)}: ${renderNode(`${path}.${name}`, k, indent + "  ")};\n`).join("")}${indent}}`;
  if (!n.tag) return body;
  const tag = `import("@abfc/runtime").GameplayTag<${JSON.stringify(path)}>`;
  return kids.length === 0 ? tag : `${tag} & ${body}`;
}

/**
 * The text of `.abfc/tags.d.ts` for the (deduplicated, sorted) tags: one `declare const <Root>` per root segment that is a plain
 * identifier and no reserved word (other roots are left out of the constants, not out of `AbfcKnownGameplayTags`), and the interface
 * the `director` decorator completes from. A global script file: it has no top-level import or export.
 */
export function renderTagsDts(tags: string[]): string {
  const all = [...new Set(tags.filter((t) => t.length > 0 && t.split(".").every((s) => s.length > 0)))].sort(byText);
  const roots = new Map<string, Node>();
  for (const tag of all) {
    const segs = tag.split(".");
    if (!IDENT.test(segs[0]!) || RESERVED.has(segs[0]!)) continue;
    let level = roots;
    let node: Node | undefined;
    for (const s of segs) {
      node = level.get(s);
      if (node === undefined) {
        node = { tag: false, kids: new Map() };
        level.set(s, node);
      }
      level = node.kids;
    }
    node!.tag = true;
  }
  const lines = ["// generated by abfc (abfc stubs, abfc build); do not edit. Gameplay tags of the game and of the mod."];
  for (const [root, node] of [...roots].sort(([a], [b]) => byText(a, b))) lines.push(`declare const ${root}: ${renderNode(root, node, "")};`);
  if (all.length === 0) lines.push("interface AbfcKnownGameplayTags {}");
  else lines.push(`interface AbfcKnownGameplayTags {\n${all.map((t) => `  ${JSON.stringify(t)}: true;`).join("\n")}\n}`);
  return lines.join("\n") + "\n";
}

const tagsFile = (abfcDir: string): string => join(abfcDir, "tags.d.ts");

/** Creates `<abfcDir>/tags.d.ts` (no tags) when it is missing; `tsconfig.paths.json` lists it, so it must exist. */
export function ensureTagsFile(abfcDir: string): void {
  const file = tagsFile(abfcDir);
  if (existsSync(file)) return;
  mkdirSync(abfcDir, { recursive: true });
  writeFileSync(file, renderTagsDts([]), "utf8");
}

/** Writes `<projectDir>/.abfc/tags.d.ts` from the game's tags and the mod's tags. Returns the file. */
export function writeTagsFile(projectDir: string, gameTags: string[], modTags: string[]): string {
  const abfcDir = join(projectDir, ".abfc");
  mkdirSync(abfcDir, { recursive: true });
  const file = tagsFile(abfcDir);
  const text = renderTagsDts([...gameTags, ...modTags]);
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text, "utf8");
  return file;
}

const GAME_TAGS_FILE = "gameplay-tags.json";

/** Stores the game's tags below `.abfc/stubs/<profile>/` (rewritten by every `abfc stubs`). */
export function writeGameTags(profileDir: string, tags: string[]): void {
  mkdirSync(profileDir, { recursive: true });
  writeFileSync(join(profileDir, GAME_TAGS_FILE), JSON.stringify([...new Set(tags)].sort(byText), null, 2) + "\n", "utf8");
}

/** The stored game tags; empty when `abfc stubs` has not stored any (old stubs, or a backend without the capability). */
export function readGameTags(profileDir: string): string[] {
  try {
    const parsed: unknown = JSON.parse(readFileSync(join(profileDir, GAME_TAGS_FILE), "utf8"));
    return Array.isArray(parsed) ? parsed.filter((t): t is string => typeof t === "string") : [];
  } catch {
    return [];
  }
}

/** The tags listed in `<projectDir>/.abfc/tags.d.ts` (the keys of `AbfcKnownGameplayTags`); empty when the file is missing. */
export function readTagsFileTags(projectDir: string): string[] {
  try {
    const out: string[] = [];
    for (const line of readFileSync(tagsFile(join(projectDir, ".abfc")), "utf8").split(/\r?\n/)) {
      const m = /^ {2}("(?:[^"\\]|\\.)*"): true;$/.exec(line);
      if (m !== null) out.push(JSON.parse(m[1]!) as string);
    }
    return out;
  } catch {
    return [];
  }
}
