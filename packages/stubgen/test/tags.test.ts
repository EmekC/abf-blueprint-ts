import { test } from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import ts from "typescript";
import { ensureTagsFile, parseTagsIni, readGameTags, renderTagsDts, writeGameTags, writeTagsFile, writeTsconfigPaths } from "../src/index.js";

const TAGS = ["ClassManager.EntityDirector.Known", "ClassManager.EntityDirector", "Ability.Fire", "Weird-Root.X", "class.Hidden", "Ability.2fast"];

test("renderTagsDts: nested readonly constants, a tag that is also a parent, quoted members, reserved and non-identifier roots skipped", () => {
  const text = renderTagsDts(TAGS);
  assert.match(text, /^\/\/ generated by abfc/);
  assert.match(text, /^declare const Ability: \{$/m);
  assert.match(text, /^ {2}readonly Fire: import\("@abfc\/runtime"\)\.GameplayTag<"Ability\.Fire">;$/m);
  assert.match(text, /^ {2}readonly "2fast": import\("@abfc\/runtime"\)\.GameplayTag<"Ability\.2fast">;$/m);
  assert.match(text, /^declare const ClassManager: \{$/m);
  assert.match(text, /^ {2}readonly EntityDirector: import\("@abfc\/runtime"\)\.GameplayTag<"ClassManager\.EntityDirector"> & \{$/m);
  assert.match(text, /^ {4}readonly Known: import\("@abfc\/runtime"\)\.GameplayTag<"ClassManager\.EntityDirector\.Known">;$/m);
  assert.doesNotMatch(text, /declare const (class|Weird)/);
  // every tag is still a key of the interface, including the ones without a constant
  assert.match(text, /^interface AbfcKnownGameplayTags \{$/m);
  for (const t of TAGS) assert.ok(text.includes(`  ${JSON.stringify(t)}: true;`), t);
  assert.doesNotMatch(text, /^(import|export) /m, "a global script file");
  assert.equal(renderTagsDts([...TAGS].reverse()), text, "sorted: the input order does not matter");
});

test("renderTagsDts: a root that is a global of the ES lib gets no constant (it would merge with the lib) but stays a key of AbfcKnownGameplayTags", () => {
  const text = renderTagsDts(["Map.Foo", "Error.Fatal", "Symbol", "Mapx.Foo"]);
  assert.doesNotMatch(text, /declare const (Map|Error|Symbol):/);
  assert.match(text, /^declare const Mapx: \{$/m);
  for (const t of ["Map.Foo", "Error.Fatal", "Symbol"]) assert.ok(text.includes(`  ${JSON.stringify(t)}: true;`), t);
});

test("renderTagsDts: no tags is an empty interface; empty segments are dropped", () => {
  assert.equal(renderTagsDts([]), "// generated by abfc (abfc stubs, abfc build); do not edit. Gameplay tags of the game and of the mod.\ninterface AbfcKnownGameplayTags {}\n");
  assert.doesNotMatch(renderTagsDts(["A..B", ""]), /declare const|"A\.\.B"/);
});

test("parseTagsIni: GameplayTagList lines with or without +, CRLF, other keys and sections ignored", () => {
  const ini = [
    "[/Script/GameplayTags.GameplayTagsSettings]",
    '+GameplayTagList=(Tag="Alpha.One",DevComment="Tag=\\"not me\\"")',
    '+GameplayTagList=(Tag="Alpha.Two",DevComment="")',
    'GameplayTagList=(Tag="Beta")',
    '+GameplayTagList=(Tag="Alpha.One",DevComment="again")',
    '; +GameplayTagList=(Tag="Commented")',
    'ImportTagsFromConfig=True',
    "",
  ].join("\r\n");
  assert.deepEqual(parseTagsIni(ini), ["Alpha.One", "Alpha.Two", "Beta"]);
  assert.deepEqual(parseTagsIni(ini.replaceAll("\r\n", "\n")), ["Alpha.One", "Alpha.Two", "Beta"]);
  assert.deepEqual(parseTagsIni(""), []);
});

test("writeTagsFile merges the game and mod tags into .abfc/tags.d.ts; ensureTagsFile keeps an existing file; the game list round-trips", () => {
  const dir = mkdtempSync(join(tmpdir(), "abfc-tags-"));
  try {
    const file = writeTagsFile(dir, ["B.One", "A.One"], ["A.One", "C.Two"]);
    assert.equal(file, join(dir, ".abfc", "tags.d.ts"));
    const text = readFileSync(file, "utf8");
    assert.equal(text, renderTagsDts(["A.One", "B.One", "C.Two"]));
    ensureTagsFile(join(dir, ".abfc"));
    assert.equal(readFileSync(file, "utf8"), text);

    const fresh = join(dir, "other", ".abfc");
    ensureTagsFile(fresh);
    assert.equal(readFileSync(join(fresh, "tags.d.ts"), "utf8"), renderTagsDts([]));

    const profile = join(dir, ".abfc", "stubs", "p1");
    assert.deepEqual(readGameTags(profile), [], "no stored list");
    writeGameTags(profile, ["Z.Last", "A.First", "A.First"]);
    assert.deepEqual(readGameTags(profile), ["A.First", "Z.Last"]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("writeTsconfigPaths lists ./tags.d.ts in files and creates it when missing", () => {
  const dir = mkdtempSync(join(tmpdir(), "abfc-tags-"));
  try {
    const abfcDir = join(dir, ".abfc");
    const file = writeTsconfigPaths(abfcDir, "p1", "TestMod", "C:\\fake\\runtime\\index.d.ts", "C:\\fake\\testkit\\index.d.ts");
    assert.deepEqual((JSON.parse(readFileSync(file, "utf8")) as { files: string[] }).files, ["./tags.d.ts"]);
    assert.ok(existsSync(join(abfcDir, "tags.d.ts")));
    // an existing tags file (with tags) is not overwritten
    writeTagsFile(dir, ["A.One"], []);
    writeTsconfigPaths(abfcDir, "p1", "TestMod", "C:\\fake\\runtime\\index.d.ts", "C:\\fake\\testkit\\index.d.ts");
    assert.match(readFileSync(join(abfcDir, "tags.d.ts"), "utf8"), /"A\.One": true/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

const req = createRequire(import.meta.url);
const dts = (spec: string): string => req.resolve(spec).replace(/\.js$/, ".d.ts");

/** An init-style project: tsconfig.json extends ./.abfc/tsconfig.paths.json and has `include` but no `files`. */
function initStyleProject(dir: string, source: string): string {
  const abfcDir = join(dir, ".abfc");
  writeTsconfigPaths(abfcDir, "p1", "TestMod", dts("@abfc/runtime"), dts("@abfc/ir"));
  writeTagsFile(dir, [], ["ClassManager.EntityDirector.Known"]);
  mkdirSync(join(dir, "src"));
  writeFileSync(join(dir, "src", "a.ts"), source);
  const cfg = join(dir, "tsconfig.json");
  writeFileSync(
    cfg,
    JSON.stringify({
      extends: "./.abfc/tsconfig.paths.json",
      compilerOptions: { module: "nodenext", moduleResolution: "nodenext", target: "es2023", strict: true, noEmit: true, types: [], skipLibCheck: true },
      include: ["src"],
    }),
  );
  return cfg;
}

test("an init-style tsconfig inherits `files` of the generated paths config: .abfc/tags.d.ts is a root file and its constants type-check", () => {
  const dir = mkdtempSync(join(tmpdir(), "abfc-tags-"));
  try {
    const cfg = initStyleProject(
      dir,
      [
        'import type { GameplayTag } from "@abfc/runtime";',
        'export const t: GameplayTag<"ClassManager.EntityDirector.Known"> = ClassManager.EntityDirector.Known;',
        'export const k: keyof AbfcKnownGameplayTags = "ClassManager.EntityDirector.Known";',
        "",
      ].join("\n"),
    );
    const parsed = ts.getParsedCommandLineOfConfigFile(cfg, {}, {
      ...ts.sys,
      onUnRecoverableConfigFileDiagnostic: (d) => {
        throw new Error(ts.flattenDiagnosticMessageText(d.messageText, "\n"));
      },
    });
    assert.ok(parsed);
    assert.deepEqual(parsed.errors.map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n")), []);
    const names = parsed.fileNames.map((f) => f.replaceAll("\\", "/").slice(dir.replaceAll("\\", "/").length));
    assert.ok(names.includes("/.abfc/tags.d.ts"), names.join(", "));
    assert.ok(names.includes("/src/a.ts"), names.join(", "));
    const program = ts.createProgram({ rootNames: parsed.fileNames, options: parsed.options });
    const problems = ts.getPreEmitDiagnostics(program).map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n"));
    assert.deepEqual(problems, []);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
